def check_ue4ss(game_dir: str) -> dict:
    """Check if UE4SS is installed in the given game directory."""
    game_path = Path(game_dir)
    markers = [
        game_path / "ue4ss" / "UE4SS.dll",
        game_path / "Binaries" / "Win64" / "UE4SS.dll",
        game_path / "Binaries" / "Win64" / "dwmapi.dll",  # proxy DLL
    ]
    # Also look for the mods folder
    mod_dirs = [
        game_path / "ue4ss" / "Mods",
        game_path / "Binaries" / "Win64" / "Mods",
    ]

    found_dll = next((str(p) for p in markers if p.exists()), None)
    found_mods = next((str(p) for p in mod_dirs if p.exists()), None)

    if found_dll:
        return {
            "installed": True,
            "dll": found_dll,
            "mods_dir": found_mods,
            "hint": "UE4SS detected. Use scaffold_map_editor() to create a mod.",
        }
    else:
        return {
            "installed": False,
            "hint": (
                "UE4SS not found. Download from https://github.com/UE4SS-RE/RE-UE4SS/releases "
                "and place UE4SS.dll + ue4ss/ folder next to game .exe. "
                "For STALKER 2: Stalker2\\Binaries\\Win64\\"
            ),
        }


def scaffold_mod(
    output_dir: str,
    mod_name: str,
    description: str = "Custom mod",
    version: str = "1.0.0",
) -> dict:
    """Create a generic UE4SS Lua mod scaffold."""
    out = Path(output_dir) / mod_name
    scripts = out / "scripts"
    scripts.mkdir(parents=True, exist_ok=True)

    main_lua = scripts / "main.lua"
    main_lua.write_text(
        _LUA_MOD_MAIN.format(
            mod_name=mod_name,
            version=version,
            description=description,
        ),
        encoding="utf-8",
    )

    enabled = out / "enabled.txt"
    enabled.write_text("", encoding="utf-8")

    return {
        "mod_dir": str(out),
        "files": [str(main_lua), str(enabled)],
        "hint": f"Copy '{out}' to your game's Mods/ directory",
    }


def scaffold_map_editor(
    output_dir: str,
    game_dir: Optional[str] = None,
    save_path: Optional[str] = None,
) -> dict:
    """
    Create the STALKER 2 Map & Object Editor mod.
    If game_dir is provided, also deploys directly to game's Mods/ folder.
    """
    out = Path(output_dir) / "MapEditor"
    scripts = out / "scripts"
    scripts.mkdir(parents=True, exist_ok=True)

    if not save_path:
        save_path = str(BASE_DIR / "output" / "map_placements.json")

    main_lua = scripts / "main.lua"
    main_lua.write_text(
        _LUA_MAP_EDITOR.replace("{save_path}", save_path.replace("\\", "\\\\")),
        encoding="utf-8",
    )
    (out / "enabled.txt").write_text("", encoding="utf-8")

    result = {
        "mod_dir": str(out),
        "save_path": save_path,
        "files": [str(main_lua)],
        "deployed": False,
    }

    if game_dir:
        # Try to find Mods directory
        gp = Path(game_dir)
        mod_destinations = [
            gp / "ue4ss" / "Mods",
            gp / "Binaries" / "Win64" / "Mods",
        ]
        dest = next((p for p in mod_destinations if p.exists()), None)
        if dest:
            deploy_path = dest / "MapEditor"
            if deploy_path.exists():
                shutil.rmtree(deploy_path)
            shutil.copytree(str(out), str(deploy_path))
            result["deployed"] = True
            result["deploy_path"] = str(deploy_path)
            result["hint"] = "Mod deployed! Launch game, open console with ~, type 'mapedit'"
        else:
            result["hint"] = (
                "Could not find Mods/ directory in game folder. "
                "Copy the mod manually or install UE4SS first."
            )

    return result


def list_mods(game_dir: str) -> dict:
    """List all UE4SS mods in a game directory."""
    gp = Path(game_dir)
    mod_dirs = [
        gp / "ue4ss" / "Mods",
        gp / "Binaries" / "Win64" / "Mods",
    ]
    mods_path = next((p for p in mod_dirs if p.exists()), None)
    if not mods_path:
        return {"error": "No Mods/ directory found. Is UE4SS installed?"}

    mods = []
    for item in mods_path.iterdir():
        if item.is_dir():
            enabled = (item / "enabled.txt").exists()
            scripts = list((item / "scripts").glob("*.lua")) if (item / "scripts").exists() else []
            mods.append({
                "name": item.name,
                "enabled": enabled,
                "lua_files": [s.name for s in scripts],
                "path": str(item),
            })

    return {"mods_dir": str(mods_path), "mods": mods, "count": len(mods)}


def enable_mod(game_dir: str, mod_name: str, enable: bool = True) -> dict:
    """Enable or disable a UE4SS mod by creating/removing enabled.txt."""
    gp = Path(game_dir)
    mod_dirs = [
        gp / "ue4ss" / "Mods" / mod_name,
        gp / "Binaries" / "Win64" / "Mods" / mod_name,
    ]
    mod_path = next((p for p in mod_dirs if p.exists()), None)
    if not mod_path:
        return {"error": f"Mod '{mod_name}' not found in {game_dir}"}

    enabled_file = mod_path / "enabled.txt"
    if enable:
        enabled_file.write_text("", encoding="utf-8")
    else:
        if enabled_file.exists():
            enabled_file.unlink()

    return {"mod": mod_name, "enabled": enable, "path": str(mod_path)}
