"""
ue4ss_helper.py — UE4SS integration for Lua mod scaffolding and deployment.

UE4SS is an open-source UE4/UE5 scripting system that allows Lua mods with:
  - Full reflection access (UObject, AActor, UWorld)
  - ImGui overlay UI
  - Blueprint override
  - Custom game-side console commands

This module:
  1. Generates Lua mod template files for UE4SS
  2. Scaffolds a map/object editor mod for STALKER 2
  3. Deploys mods to the game's Mods/ directory
  4. Checks for UE4SS installation in a game directory
"""

